/**
 * Writes docs/kannada-review.md: every English string beside its Kannada, grouped by screen.
 *
 * The point is that someone who reads Kannada can go through the whole interface without opening
 * a code file, mark up the ones that read wrong, and hand it back. Corrections go into the KN
 * block of shared/src/i18n.ts.
 *
 *   node scripts/gen-i18n-review.js
 */
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const BUILD = path.join(ROOT, '.i18nreview-build');
const OUT = path.join(ROOT, 'docs', 'kannada-review.md');

const tsc = path.join(ROOT, 'node_modules', 'typescript', 'bin', 'tsc');
fs.rmSync(BUILD, { recursive: true, force: true });
execFileSync(process.execPath, [
  tsc, 'shared/src/i18n.ts',
  '--outDir', BUILD, '--module', 'commonjs', '--target', 'es2019',
  '--strict', '--skipLibCheck', '--lib', 'es2019,dom',
], { cwd: ROOT, stdio: 'inherit' });

const { STRINGS, receiptLabelsFor } = require(path.join(BUILD, 'i18n.js'));

/** Prefix → the screen a reviewer would recognise it by. */
const GROUPS = [
  ['common', 'Buttons that appear everywhere'],
  ['nav', 'The tabs along the bottom'],
  ['app', 'Top bar'],
  ['login', 'Sign-in screen'],
  ['bill', 'Bill screen'],
  ['cust', 'Customer box at the top of the bill'],
  ['ink', 'Handwriting pad'],
  ['kni', 'Typing Kannada with English letters'],
  ['items', 'Items screen'],
  ['cs', 'Customers screen'],
  ['hist', 'History screen'],
  ['set', 'Settings screen'],
];

/** A cell that will not break the table or hide leading/trailing spaces. */
function cell(text) {
  const marked = text.replace(/^ | $/g, '␣');
  return marked.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

const en = STRINGS.en;
const kn = STRINGS.kn;
const keys = Object.keys(en);

const lines = [];
lines.push('# Kannada review sheet');
lines.push('');
lines.push('Every word the app shows, English on the left, Kannada on the right.');
lines.push('');
lines.push('**How to use this.** Read down the Kannada column. Where the wording is wrong, awkward,');
lines.push('or too formal for a shop counter, write the better version next to it. You do not need to');
lines.push('look at any code — the `Key` column is only there so a correction can be applied to the');
lines.push('right string.');
lines.push('');
lines.push('Two things to watch for:');
lines.push('');
lines.push('- `{n}`, `{amount}`, `{name}`, `{days}`, `{no}`, `{date}`, `{mm}`, `{dots}`, `{reason}`,');
lines.push('  `{what}` are filled in by the app. Keep them exactly as they are, but move them if');
lines.push('  Kannada word order needs it.');
lines.push('- `␣` marks a space at the start or end of a string that has to stay there.');
lines.push('');
lines.push('Generated by `npm run i18n:review` — do not edit this file by hand, edit the `KN` block in');
lines.push('`shared/src/i18n.ts` and regenerate.');
lines.push('');
lines.push('## What prints on the receipt');
lines.push('');
lines.push('These are the words on the paper the customer takes away, so they matter most.');
lines.push('');
lines.push('| English | Kannada |');
lines.push('| --- | --- |');
const enLabels = receiptLabelsFor('en');
const knLabels = receiptLabelsFor('kn');
for (const field of Object.keys(enLabels)) {
  lines.push('| ' + cell(enLabels[field]) + ' | ' + cell(knLabels[field]) + ' |');
}
lines.push('');

const seen = new Set();
for (const [prefix, title] of GROUPS) {
  const group = keys.filter((k) => k.startsWith(prefix + '.'));
  if (group.length === 0) continue;
  lines.push('## ' + title);
  lines.push('');
  lines.push('| Key | English | Kannada |');
  lines.push('| --- | --- | --- |');
  for (const key of group) {
    seen.add(key);
    lines.push('| `' + key + '` | ' + cell(en[key]) + ' | ' + cell(kn[key]) + ' |');
  }
  lines.push('');
}

const ungrouped = keys.filter((k) => !seen.has(k));
if (ungrouped.length > 0) {
  lines.push('## Everything else');
  lines.push('');
  lines.push('| Key | English | Kannada |');
  lines.push('| --- | --- | --- |');
  for (const key of ungrouped) {
    lines.push('| `' + key + '` | ' + cell(en[key]) + ' | ' + cell(kn[key]) + ' |');
  }
  lines.push('');
}

lines.push('---');
lines.push('');
lines.push(keys.length + ' interface strings and ' + Object.keys(enLabels).length + ' receipt labels.');
lines.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'), 'utf8');
fs.rmSync(BUILD, { recursive: true, force: true });
console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + keys.length + ' strings)');
